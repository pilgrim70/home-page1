CREATE POLICY "Allow all update news" ON news_posts_v4 FOR UPDATE USING (true);
CREATE POLICY "Allow all delete news" ON news_posts_v4 FOR DELETE USING (true);

CREATE POLICY "Allow all read school" ON school_posts_v2 FOR SELECT USING (true);
CREATE POLICY "Allow all insert school" ON school_posts_v2 FOR INSERT WITH CHECK (true);
